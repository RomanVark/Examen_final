-- SCRIPT 01. Ejecutar CONECTADO a practicas_profesionales.
-- Esquema creado de forma explícita; Hibernate usa hbm2ddl.auto=validate.
BEGIN;

-- Carrera: 4 atributos + clave primaria
CREATE TABLE IF NOT EXISTS carreras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(150) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    facultad VARCHAR(150) NOT NULL,
    activa BOOLEAN NOT NULL
);

-- Estudiante: 7 atributos + clave primaria
CREATE TABLE IF NOT EXISTS estudiantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carnet VARCHAR(150) NOT NULL UNIQUE,
    nombres VARCHAR(150) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    telefono VARCHAR(150),
    carrera_id BIGINT REFERENCES carreras(id) ON DELETE RESTRICT NOT NULL,
    activo BOOLEAN NOT NULL
);

-- Empresa: 7 atributos + clave primaria
CREATE TABLE IF NOT EXISTS empresas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc VARCHAR(150) NOT NULL UNIQUE,
    razon_social VARCHAR(150) NOT NULL,
    sector VARCHAR(150) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    telefono VARCHAR(150),
    direccion VARCHAR(500),
    activa BOOLEAN NOT NULL
);

-- TutorAcademico: 5 atributos + clave primaria
CREATE TABLE IF NOT EXISTS tutores_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(150) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    especialidad VARCHAR(150) NOT NULL,
    activo BOOLEAN NOT NULL
);

-- SupervisorEmpresa: 6 atributos + clave primaria
CREATE TABLE IF NOT EXISTS supervisores_empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(150) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    cargo VARCHAR(150) NOT NULL,
    empresa_id BIGINT NOT NULL,
    activo BOOLEAN NOT NULL,
    CONSTRAINT fk_supervisores_empresa_empresa
        FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE RESTRICT
);

-- Convenio: 5 atributos + clave primaria
CREATE TABLE IF NOT EXISTS convenios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(150) NOT NULL UNIQUE,
    empresa_id BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(32) NOT NULL,
    CONSTRAINT fk_convenios_empresa_empresa
        FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE RESTRICT,
    CONSTRAINT ck_convenios_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_convenios_estado CHECK (estado IN ('VIGENTE', 'VENCIDO', 'SUSPENDIDO'))
);

-- OfertaPractica: 8 atributos + clave primaria
CREATE TABLE IF NOT EXISTS ofertas_practica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(150) NOT NULL UNIQUE,
    titulo VARCHAR(150) NOT NULL,
    descripcion VARCHAR(4000),
    empresa_id BIGINT REFERENCES empresas(id) ON DELETE RESTRICT NOT NULL,
    cupos INTEGER NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(32) NOT NULL,
    CONSTRAINT ck_ofertas_practica_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_oferta_cupos CHECK (cupos > 0),
    CONSTRAINT ck_ofertas_practica_estado CHECK (estado IN ('ABIERTA', 'CERRADA', 'CANCELADA'))
);

-- Postulacion: 5 atributos + clave primaria
CREATE TABLE IF NOT EXISTS postulaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT REFERENCES estudiantes(id) ON DELETE RESTRICT NOT NULL,
    oferta_id BIGINT REFERENCES ofertas_practica(id) ON DELETE RESTRICT NOT NULL,
    fecha DATE NOT NULL,
    estado VARCHAR(32) NOT NULL,
    observaciones VARCHAR(4000),
    CONSTRAINT uq_postulaciones_par UNIQUE (estudiante_id, oferta_id),
    CONSTRAINT ck_postulaciones_estado CHECK (estado IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA'))
);

-- Practica: 8 atributos + clave primaria
CREATE TABLE IF NOT EXISTS practicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT REFERENCES estudiantes(id) ON DELETE RESTRICT NOT NULL,
    oferta_id BIGINT REFERENCES ofertas_practica(id) ON DELETE RESTRICT NOT NULL,
    tutor_academico_id BIGINT REFERENCES tutores_academicos(id) ON DELETE RESTRICT NOT NULL,
    supervisor_empresa_id BIGINT REFERENCES supervisores_empresa(id) ON DELETE RESTRICT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    horas_requeridas INTEGER NOT NULL,
    estado VARCHAR(32) NOT NULL,
    CONSTRAINT uq_practicas_par UNIQUE (estudiante_id, oferta_id),
    CONSTRAINT ck_practicas_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT ck_practica_horas CHECK (horas_requeridas > 0),
    CONSTRAINT ck_practicas_estado CHECK (estado IN ('PLANIFICADA', 'EN_CURSO', 'FINALIZADA', 'SUSPENDIDA'))
);

-- Bitacora: 5 atributos + clave primaria
CREATE TABLE IF NOT EXISTS bitacoras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practica_id BIGINT REFERENCES practicas(id) ON DELETE RESTRICT NOT NULL,
    fecha DATE NOT NULL,
    actividad VARCHAR(4000) NOT NULL,
    horas INTEGER NOT NULL,
    validada BOOLEAN NOT NULL,
    CONSTRAINT ck_bitacora_horas CHECK (horas BETWEEN 1 AND 24)
);

-- Evaluacion: 5 atributos + clave primaria
CREATE TABLE IF NOT EXISTS evaluaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practica_id BIGINT REFERENCES practicas(id) ON DELETE RESTRICT NOT NULL,
    fecha DATE NOT NULL,
    evaluador VARCHAR(150) NOT NULL,
    calificacion NUMERIC(5,2) NOT NULL,
    observaciones VARCHAR(4000),
    CONSTRAINT ck_evaluacion_nota CHECK (calificacion BETWEEN 0 AND 100)
);

-- Documento: 6 atributos + clave primaria
CREATE TABLE IF NOT EXISTS documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practica_id BIGINT REFERENCES practicas(id) ON DELETE RESTRICT NOT NULL,
    tipo VARCHAR(150) NOT NULL,
    nombre_archivo VARCHAR(150) NOT NULL,
    ruta_archivo VARCHAR(500) NOT NULL,
    fecha_entrega DATE NOT NULL,
    verificado BOOLEAN NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_estudiantes_carrera_id ON estudiantes (carrera_id);
CREATE INDEX IF NOT EXISTS idx_supervisores_empresa_empresa_id ON supervisores_empresa (empresa_id);
CREATE INDEX IF NOT EXISTS idx_convenios_empresa_id ON convenios (empresa_id);
CREATE INDEX IF NOT EXISTS idx_ofertas_practica_empresa_id ON ofertas_practica (empresa_id);
CREATE INDEX IF NOT EXISTS idx_postulaciones_estudiante_id ON postulaciones (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_postulaciones_oferta_id ON postulaciones (oferta_id);
CREATE INDEX IF NOT EXISTS idx_practicas_estudiante_id ON practicas (estudiante_id);
CREATE INDEX IF NOT EXISTS idx_practicas_oferta_id ON practicas (oferta_id);
CREATE INDEX IF NOT EXISTS idx_practicas_tutor_academico_id ON practicas (tutor_academico_id);
CREATE INDEX IF NOT EXISTS idx_practicas_supervisor_empresa_id ON practicas (supervisor_empresa_id);
CREATE INDEX IF NOT EXISTS idx_bitacoras_practica_id ON bitacoras (practica_id);
CREATE INDEX IF NOT EXISTS idx_evaluaciones_practica_id ON evaluaciones (practica_id);
CREATE INDEX IF NOT EXISTS idx_documentos_practica_id ON documentos (practica_id);

COMMIT;
