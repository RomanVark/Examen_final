-- Esta tabla adicional no altera las doce tablas originales.
BEGIN;
CREATE TABLE IF NOT EXISTS api_consumos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instante TIMESTAMP WITH TIME ZONE NOT NULL,
    metodo VARCHAR(10) NOT NULL,
    ruta VARCHAR(200) NOT NULL,
    codigo_http INTEGER NOT NULL,
    duracion_ms BIGINT NOT NULL,
    CONSTRAINT ck_api_consumo_codigo CHECK (codigo_http BETWEEN 100 AND 599),
    CONSTRAINT ck_api_consumo_duracion CHECK (duracion_ms >= 0)
);
CREATE INDEX IF NOT EXISTS idx_api_consumos_instante ON api_consumos(instante DESC);
COMMIT;
